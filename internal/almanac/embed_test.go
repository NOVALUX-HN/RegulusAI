package almanac

import (
	"strings"
	"testing"
)

func TestEmbedDimIs384(t *testing.T) {
	if EmbedDim != 384 {
		t.Fatalf("EmbedDim = %d, want 384 (docs/memory-v2.md §4)", EmbedDim)
	}
}

func TestEmbedDeterministic(t *testing.T) {
	a := Embed("the quick brown fox jumps over the lazy dog")
	b := Embed("the quick brown fox jumps over the lazy dog")
	if a != b {
		t.Fatal("same text must embed to the same vector twice")
	}
	c := Embed("the quick brown fox jumps over the lazy dog!")
	if a == c {
		t.Fatal("different texts should (almost surely) embed differently")
	}
}

func TestEmbedEmptyIsZero(t *testing.T) {
	v := Embed("")
	for i, b := range v {
		if b != 0 {
			t.Fatalf("empty text must embed to the zero vector, byte %d = %d", i, b)
		}
	}
}

func TestEmbedFixtureVectors(t *testing.T) {
	// Pinned across processes: the same input must produce the same
	// bytes in every process, every run. These were generated by the
	// reference implementation and must never change without a version
	// bump + reindex.
	v := Embed("hello world")
	// Non-zero: a real input must activate buckets.
	nonZero := 0
	for _, b := range v {
		if b != 0 {
			nonZero++
		}
	}
	if nonZero == 0 {
		t.Fatal("hello world must activate buckets")
	}
	// Fixture: first 16 quantized bytes, pinned to catch accidental
	// encoder changes. Regenerate only with an explicit version bump.
	wantHello := [16]int8{0, 0, 0, 0, 0, 0, 0, 0, 0, -26, 0, 26, 0, 0, 0, 0}
	for i, want := range wantHello {
		if v[i] != want {
			t.Fatalf("fixture vector mismatch at byte %d: got %d, want %d (encoder changed — bump version + reindex)", i, v[i], want)
		}
	}
	wantFox := [16]int8{0, 0, 0, 0, 12, -12, 12, 0, 0, 0, 0, 0, 0, -23, -12, -12}
	fox := Embed("the quick brown fox jumps over the lazy dog")
	for i, want := range wantFox {
		if fox[i] != want {
			t.Fatalf("fixture vector mismatch (fox) at byte %d: got %d, want %d", i, fox[i], want)
		}
	}
}

func TestEmbedCaseInsensitive(t *testing.T) {
	if Embed("Hello World") != Embed("hello world") {
		t.Fatal("embedder must be case-insensitive (lowercases before hashing)")
	}
}

func TestEmbedObservationUsesTitleAndContent(t *testing.T) {
	a := EmbedObservation(Observation{Title: "chose postgres", Content: "pooling everywhere"})
	b := Embed("chose postgres\npooling everywhere")
	if a != b {
		t.Fatal("EmbedObservation must embed title + newline + content")
	}
	if a == Embed("unrelated text with no overlap xyzzy") && strings.Contains("x", "x") {
		t.Fatal("unrelated text should differ")
	}
}
